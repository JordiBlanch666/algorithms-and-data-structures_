"""
Generates sql/seed.sql with fictional support tickets (fixed seed = reproducible).

    python scripts/generate_data.py
"""
import random
from datetime import datetime, timedelta
from pathlib import Path

random.seed(7)
OUTPUT = Path(__file__).resolve().parent.parent / "sql" / "seed.sql"

DEPARTMENTS = ["Sales", "Finance", "Human Resources", "Operations", "Marketing", "Management"]
AGENTS = [("Laura Méndez", "L1"), ("Iván Torres", "L1"), ("Karla Ruiz", "L1"),
          ("Tomás Aguilar", "L2"), ("Beatriz Soto", "L2"), ("Rodrigo Leal", "L3")]
CATEGORIES = {
    "Passwords & access": ["Password reset", "Account locked", "Shared folder access"],
    "Email": ["Emails not arriving", "Set up Outlook on phone", "Mailbox full"],
    "Hardware": ["Laptop won't turn on", "Monitor has no signal", "Broken keyboard"],
    "Printers": ["Paper jam", "Can't print over network", "Install printer"],
    "Network & VPN": ["No internet", "VPN won't connect", "Slow Wi-Fi"],
    "Software": ["Install Office", "ERP error", "Update antivirus"],
}
SLA = [("Critical", 1, 4), ("High", 2, 8), ("Medium", 4, 24), ("Low", 8, 72)]
FIRST_NAMES = ["Ana", "Luis", "Marta", "Pedro", "Rosa", "Juan", "Elsa", "Hugo", "Nora", "Raúl",
               "Silvia", "Adrián", "Celia", "Mario", "Lorena", "Víctor", "Irene", "Gustavo"]
LAST_NAMES = ["Ortiz", "Vega", "Castro", "Navarro", "Ríos", "Salinas", "Mora", "Campos", "Rojas"]

START = datetime(2026, 5, 4, 8, 0)
END = datetime(2026, 10, 30, 18, 0)


def q(v):
    return "NULL" if v is None else "'" + str(v).replace("'", "''") + "'"


def fmt(dt):
    return dt.strftime("%Y-%m-%d %H:%M:%S") if dt else None


def business_hour():
    day = START + timedelta(days=random.randint(0, (END - START).days))
    while day.weekday() >= 5:
        day += timedelta(days=1)
    return day.replace(hour=random.randint(8, 17), minute=random.randint(0, 59))


def main():
    sql = ["-- Fictional data generated by scripts/generate_data.py (seed 7)",
           "BEGIN TRANSACTION;", ""]
    sql += [f"INSERT INTO departments VALUES ({i}, {q(n)});" for i, n in enumerate(DEPARTMENTS, 1)]
    sql += [f"INSERT INTO agents VALUES ({i}, {q(n)}, {q(t)}, 1);" for i, (n, t) in enumerate(AGENTS, 1)]
    sql += [f"INSERT INTO categories VALUES ({i}, {q(n)});" for i, n in enumerate(CATEGORIES, 1)]
    sql += [f"INSERT INTO sla VALUES ({q(p)}, {r}, {s});" for p, r, s in SLA]
    sql.append("")

    used = set()
    for uid in range(1, 61):
        while True:
            name = f"{random.choice(FIRST_NAMES)} {random.choice(LAST_NAMES)}"
            if name not in used:
                used.add(name)
                break
        email = name.lower().replace(" ", ".")
        for a, b in zip("áéíóú", "aeiou"):
            email = email.replace(a, b)
        sql.append(f"INSERT INTO users VALUES ({uid}, {q(name)}, {q(email + '@company.com')}, "
                   f"{random.randint(1, len(DEPARTMENTS))});")
    sql.append("")

    # A few users open many more tickets (as in real life)
    user_weights = [random.choice([1, 1, 1, 2, 5]) for _ in range(60)]
    categories = list(CATEGORIES)
    speed = {1: 1.0, 2: 0.8, 3: 1.4, 4: 1.1, 5: 0.9, 6: 1.2}   # each agent's speed factor

    for tid in range(1, 501):
        cat_id = random.choices(range(1, 7), weights=[30, 15, 10, 15, 15, 15])[0]
        title = random.choice(CATEGORIES[categories[cat_id - 1]])
        priority, h_resp, h_res = random.choices(SLA, weights=[5, 20, 50, 25])[0]
        created = business_hour()
        user = random.choices(range(1, 61), weights=user_weights)[0]
        agent = random.choices(range(1, 7), weights=[25, 25, 20, 12, 12, 6])[0]

        age_days = (END - created).days
        if age_days < 6 and random.random() < 0.8:
            status = random.choice(["Open", "Open", "In progress"])
        elif age_days < 21 and random.random() < 0.25:
            status = "On hold"
        else:
            status = random.choice(["Resolved", "Closed", "Closed"])
        if status == "Open" and random.random() < 0.5:
            agent = None

        response = resolved = score = None
        if agent:
            response = created + timedelta(minutes=int(random.uniform(5, h_resp * 80) * speed[agent]))
        if status in ("Resolved", "Closed"):
            resolved = response + timedelta(minutes=int(random.uniform(20, h_res * 70) * speed[agent]))
            score = random.choices([5, 4, 3, 2, 1], weights=[45, 30, 12, 8, 5])[0]
            if resolved - created > timedelta(hours=h_res):
                score = max(1, score - 2)
            if random.random() < 0.3:
                score = None   # not everyone answers the survey

        sql.append(
            f"INSERT INTO tickets VALUES ({tid}, {user}, {agent or 'NULL'}, {cat_id}, {q(priority)}, "
            f"{q(title)}, {q(status)}, {q(fmt(created))}, {q(fmt(response))}, {q(fmt(resolved))}, "
            f"{score if score else 'NULL'});")

    sql += ["", "COMMIT;"]
    OUTPUT.write_text("\n".join(sql) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
