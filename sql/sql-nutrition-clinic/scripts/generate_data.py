"""
Generates sql/seed.sql with fictional but realistic data.
Uses a fixed random seed so the results are reproducible.

    python scripts/generate_data.py
"""
import random
from datetime import date, timedelta
from pathlib import Path

random.seed(42)
OUTPUT = Path(__file__).resolve().parent.parent / "sql" / "seed.sql"

FEMALE_NAMES = ["Ana", "María", "Lucía", "Sofía", "Fernanda", "Valeria", "Gabriela", "Daniela",
                "Paola", "Andrea", "Mariana", "Rocío", "Claudia", "Patricia", "Elena"]
MALE_NAMES = ["Luis", "Carlos", "Jorge", "Miguel", "Raúl", "Andrés", "Diego", "Javier",
              "Ricardo", "Fernando", "Héctor", "Emilio", "Sergio", "Óscar", "Pablo"]
LAST_NAMES = ["García", "Hernández", "Martínez", "López", "González", "Pérez", "Rodríguez",
              "Sánchez", "Ramírez", "Cruz", "Flores", "Morales", "Reyes", "Jiménez", "Vargas"]
CITIES = ["San Juan del Río", "Tequisquiapan", "Querétaro", "Pedro Escobedo", "Ezequiel Montes"]
CONDITIONS = ["Type 2 diabetes", "Hypertension", "Dyslipidemia", "Hypothyroidism",
              "Polycystic ovary syndrome", "Fatty liver", "Insulin resistance"]
GOALS = ["weight loss", "glucose control", "muscle gain", "maintenance"]

START, END = date(2025, 1, 6), date(2026, 10, 31)


def q(text):
    return "'" + str(text).replace("'", "''") + "'"


def main():
    sql = ["-- Fictional data generated by scripts/generate_data.py (seed 42)",
           "BEGIN TRANSACTION;", ""]
    sql += [f"INSERT INTO conditions (id, name) VALUES ({i}, {q(n)});"
            for i, n in enumerate(CONDITIONS, 1)]
    sql.append("")

    appointment_id = measurement_id = plan_id = 0
    for pid in range(1, 41):
        sex = random.choice("FM")
        name = random.choice(FEMALE_NAMES if sex == "F" else MALE_NAMES)
        name += " " + " ".join(random.sample(LAST_NAMES, 2))
        birth = date(random.randint(1960, 2004), random.randint(1, 12), random.randint(1, 28))
        signup = START + timedelta(days=random.randint(0, 560))
        sql.append(
            f"INSERT INTO patients VALUES ({pid}, {q(name)}, {q(sex)}, {q(birth)}, "
            f"{q(random.choice(CITIES))}, {q(signup)});")

        # Polycystic ovary syndrome is only assigned to female patients
        allowed = [i for i, n in enumerate(CONDITIONS, 1) if sex == "F" or "ovary" not in n]
        for condition in random.sample(allowed, random.choice([0, 1, 1, 2, 3])):
            sql.append(f"INSERT INTO patient_conditions VALUES ({pid}, {condition});")

        height = round(random.uniform(1.50, 1.72) if sex == "F" else random.uniform(1.60, 1.85), 2)
        weight = round(height * height * random.uniform(23, 38), 1)
        body_fat = random.uniform(28, 42) if sex == "F" else random.uniform(20, 32)
        goal = random.choices(GOALS, weights=[6, 2, 1, 1])[0]
        trend = {"weight loss": -1.2, "glucose control": -0.6,
                 "muscle gain": 0.5, "maintenance": 0.0}[goal]

        plan_id += 1
        calories = int(round(weight * (22 if trend < 0 else 30), -1))
        calories = max(1200, min(calories, 3500))
        sql.append(f"INSERT INTO plans VALUES ({plan_id}, {pid}, {q(signup)}, {q(goal)}, {calories});")

        visit = signup
        for n in range(random.randint(1, 9)):
            if visit > END:
                break
            appointment_id += 1
            visit_type = "first visit" if n == 0 else "follow-up"
            fee = 600 if n == 0 else 450
            sql.append(f"INSERT INTO appointments VALUES ({appointment_id}, {pid}, {q(visit)}, "
                       f"{q(visit_type)}, {fee});")
            measurement_id += 1
            waist = round(weight / height ** 2 * 2.6 + 25 + random.uniform(-3, 3), 1)
            sql.append(f"INSERT INTO measurements VALUES ({measurement_id}, {appointment_id}, "
                       f"{weight}, {height}, {waist}, {round(body_fat, 1)});")
            weight = round(weight + trend + random.uniform(-0.9, 0.7), 1)
            body_fat = max(10, body_fat + trend * 0.4 + random.uniform(-0.3, 0.3))
            visit += timedelta(days=random.randint(14, 35))
        sql.append("")

    sql.append("COMMIT;")
    OUTPUT.write_text("\n".join(sql) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT} ({appointment_id} appointments)")


if __name__ == "__main__":
    main()
